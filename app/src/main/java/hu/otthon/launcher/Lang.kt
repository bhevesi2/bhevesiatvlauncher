/**
 * The launcher's language: English (the default) or Hungarian, chosen in Settings › Appearance.
 * The texts are written in English in the code; [tr] gives the Hungarian of a whole text, or of
 * a text with names and numbers in it ([rules]). Every TextView made with [label] is an [LText],
 * which translates whatever is set on it, so the screens need no changes of their own.
 */
object Lang {
    @Volatile var hu = false
        private set

    /** From the settings (config.json "language": "en" or "hu"); every process loads them. */
    fun set(code: String?) {
        hu = code == "hu"
    }

    val locale: Locale get() = if (hu) Locale("hu", "HU") else Locale.ENGLISH

    fun tr(s: String): String {
        if (!hu || s.isEmpty()) return s
        words[s]?.let { return it }
        for ((re, f) in rules) {
            val m = re.matchEntire(s) ?: continue
            return f(m.groupValues)
        }
        return s
    }

    /** A date pattern written for English, in the order and words of the chosen language. */
    fun dtf(pattern: String): DateTimeFormatter =
        DateTimeFormatter.ofPattern(if (hu) huPatterns[pattern] ?: pattern else pattern, locale)

    fun sdf(pattern: String) = java.text.SimpleDateFormat(if (hu) huPatterns[pattern] ?: pattern else pattern, locale)

